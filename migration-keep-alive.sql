-- Keep-alive para evitar que o banco Supabase seja pausado por inatividade (plano gratuito).
-- O GitHub Action executa public.keep_alive() via RPC a cada 3 dias.

-- Tabela de ping
CREATE TABLE IF NOT EXISTS public.keep_alive (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pinged_at timestamptz NOT NULL DEFAULT now()
);

-- RLS ativo, sem nenhuma policy de acesso direto.
-- Apenas a função (SECURITY DEFINER) consegue inserir/limpar registros.
ALTER TABLE public.keep_alive ENABLE ROW LEVEL SECURITY;

-- Função de ping: insere uma linha e limpa registros com mais de 30 dias
CREATE OR REPLACE FUNCTION public.keep_alive()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.keep_alive (pinged_at) VALUES (now());
    DELETE FROM public.keep_alive WHERE pinged_at < now() - interval '30 days';
END;
$$;

-- Permite que o role anon (usado pela anon key no GitHub Action) chame a função via RPC
GRANT EXECUTE ON FUNCTION public.keep_alive() TO anon;